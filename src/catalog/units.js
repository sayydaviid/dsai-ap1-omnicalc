export function enumerateConversions() {
  return dimensions.flatMap((dimension) =>
    dimension.units.flatMap((from) =>
      dimension.units.filter((to) => from.id !== to.id).map((to) => ({
        id: `${dimension.id}-${from.id}-to-${to.id}`,
        name: `${from.name} → ${to.name}`,
        category: dimension.name,
        categoryId: dimension.id,
        kind: 'conversion',
        from,
        to,
        base: dimension.base,
        absolute: dimension.absolute,
      })),
    ),
  );
}
